"""Week 5, step 1b: HPC rotor blade section (healthy and eroded) + CFD cascade files.

Blade shape: NACA 4-digit thickness laid on a circular-arc camber line.
A generic compressor section, NOT a real HPC blade (those are not public).

Blade angles from the flow angles (step 1a):
  incidence  i = 0 (flow meets the blade along its camber line)
  deviation  Carter's rule: delta = m * camber / sqrt(solidity),
             m = 0.23 + beta2_metal / 500   (circular arc, angles in deg)
  The flow leaves a few degrees off the blade angle, so the blade must be
  turned MORE than the flow. Solved by a short loop.

Wear cases for CFD (step 4):
  healthy : as designed, smooth wall
  fouled  : same shape, rough wall (sand-grain roughness KS_FOULED_UM) set in Fluent
  eroded  : front ERODE_DEPTH of the chord worn away, nose rounded off bluntly

Outputs (all regenerated by running this file):
  cfd/geometry/<case>_spaceclaim.txt   blade curve, mm, for Ansys SpaceClaim
  cfd/geometry/domain_spaceclaim.txt   periodic lines + inlet + outlet, mm
  cfd/cascade_conditions.json          boundary conditions for Fluent
  cad/blade_profiles/<case>_fusion.csv blade curve, cm, for Fusion 360
  reports/figures/13_hpc_blade_cascade.png

Run from the repo root:
    python -m src.cad_cfd.blade_geometry
"""
import json
import math
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

from src.cad_cfd.hpc_stage import Stage, design_stage

ROOT = Path(__file__).resolve().parents[2]
THICKNESS = 0.07       # max thickness / chord, typical mid-stage HPC
INCIDENCE = 0.0        # deg
ERODE_DEPTH = 0.02     # fraction of chord worn off the leading edge
KS_FOULED_UM = 40.0    # fouled sand-grain roughness, micrometres (10-60 reported)
N_SIDE = 120           # points per blade surface


def metal_angles(s: Stage) -> dict:
    """Blade (metal) angles that give the step 1a flow angles. Degrees."""
    b1_metal = s.beta1 - INCIDENCE
    b2_metal = s.beta2
    for _ in range(50):
        camber = b1_metal - b2_metal
        m = 0.23 + b2_metal / 500
        deviation = m * camber / math.sqrt(s.solidity)
        b2_metal = s.beta2 - deviation
    camber = b1_metal - b2_metal
    return {"b1_metal": b1_metal, "b2_metal": b2_metal, "camber": camber,
            "deviation": deviation, "stagger": (b1_metal + b2_metal) / 2}


def half_thickness(x):
    """NACA 4-digit half-thickness / chord at x = 0..1 (closed trailing edge)."""
    return 5 * THICKNESS * (0.2969 * np.sqrt(x) - 0.1260 * x - 0.3516 * x ** 2
                            + 0.2843 * x ** 3 - 0.1036 * x ** 4)


def camber_line(x, camber_deg):
    """Circular arc through (0,0) and (1,0), end slopes +-camber/2.
    Returns y and the local slope angle (rad), chord = 1."""
    half = math.radians(camber_deg) / 2
    if abs(half) < 1e-9:
        return np.zeros_like(x), np.zeros_like(x)
    r = 0.5 / math.sin(half)                    # arc radius
    yc = np.sqrt(r ** 2 - (x - 0.5) ** 2) - r * math.cos(half)
    slope = np.arctan2(-(x - 0.5), np.sqrt(r ** 2 - (x - 0.5) ** 2))
    return yc, slope


def to_cascade(xy, chord, stagger_deg):
    """Chord-frame points (chord = 1) -> cascade frame in metres.
    x = axial, y = tangential. Leading edge at the origin."""
    a = math.radians(stagger_deg)
    rot = np.array([[math.cos(a), -math.sin(a)], [math.sin(a), math.cos(a)]])
    return chord * xy @ rot.T


def profile(s: Stage, case: str = "healthy") -> np.ndarray:
    """Closed blade outline in the cascade frame (m): trailing edge ->
    suction side -> leading edge -> pressure side -> trailing edge."""
    ang = metal_angles(s)
    x_start = ERODE_DEPTH if case == "eroded" else 0.0
    beta = np.linspace(0, math.pi, N_SIDE)
    x = x_start + (1 - x_start) * (1 - np.cos(beta)) / 2     # points bunch at both ends
    yc, slope = camber_line(x, ang["camber"])
    yt = half_thickness(x)
    nx, ny = -np.sin(slope), np.cos(slope)                    # unit normal to camber
    upper = np.column_stack([x + yt * nx, yc + yt * ny])      # suction side (convex)
    lower = np.column_stack([x - yt * nx, yc - yt * ny])      # pressure side

    if case == "eroded":
        # Blunt nose: half-circle centred on the camber line at the cut,
        # radius = local half-thickness, joining the two surfaces round the front
        a0 = math.atan2(ny[0], nx[0])
        arc = np.linspace(a0, a0 + math.pi, 40)[1:-1]
        nose = np.column_stack([x[0] + yt[0] * np.cos(arc), yc[0] + yt[0] * np.sin(arc)])
        loop = np.vstack([upper[::-1], nose, lower[1:]])
    else:
        loop = np.vstack([upper[::-1], lower[1:]])
    return to_cascade(loop, s.chord, ang["stagger"])


def domain(s: Stage) -> dict:
    """Passage boundaries (m). The periodic lines follow the camber line half a
    pitch above and below the blade, extended 1 axial chord upstream along the
    inlet flow angle and 1.5 axial chords downstream along the exit flow angle."""
    ang = metal_angles(s)
    x = np.linspace(0, 1, 60)
    yc, _ = camber_line(x, ang["camber"])
    mid = to_cascade(np.column_stack([x, yc]), s.chord, ang["stagger"])
    cx_axial = mid[-1, 0] - mid[0, 0]
    up = np.array([-cx_axial, -cx_axial * math.tan(math.radians(s.beta1))])
    down = np.array([1.5 * cx_axial, 1.5 * cx_axial * math.tan(math.radians(s.beta2))])
    line = np.vstack([mid[0] + up, mid, mid[-1] + down])
    upper = line + [0, s.pitch / 2]
    lower = line - [0, s.pitch / 2]
    return {"periodic_upper": upper, "periodic_lower": lower,
            "inlet": np.vstack([lower[0], upper[0]]),
            "outlet": np.vstack([lower[-1], upper[-1]]),
            "axial_chord": cx_axial}


def outlet_static_pressure(s: Stage, omega: float = 0.04) -> float:
    """Rotor exit static pressure (Pa) for the CFD outlet. Relative total
    temperature is constant through the rotor (same radius); relative total
    pressure drops by an assumed clean loss omega."""
    p02 = s.p0_rel - omega * (s.p0_rel - s.p1)
    t2 = s.t0_rel - s.w2 ** 2 / (2 * s.cp)
    return p02 * (t2 / s.t0_rel) ** (s.gamma / (s.gamma - 1))


def write_spaceclaim(path: Path, curves: list) -> None:
    """SpaceClaim curve file: one block of 'x y z' (mm) per curve, blank line between."""
    lines = ["3d=true", "polyline=false", ""]
    for c in curves:
        lines += [f"{1000 * x:.5f} {1000 * y:.5f} 0" for x, y in c] + [""]
    path.write_text("\n".join(lines))


def main() -> None:
    s = design_stage()
    ang = metal_angles(s)
    dom = domain(s)
    out_cfd, out_cad = ROOT / "cfd" / "geometry", ROOT / "cad" / "blade_profiles"
    out_cfd.mkdir(parents=True, exist_ok=True)
    out_cad.mkdir(parents=True, exist_ok=True)

    shapes = {"healthy": profile(s, "healthy"), "eroded": profile(s, "eroded")}
    for name, xy in shapes.items():
        write_spaceclaim(out_cfd / f"{name}_spaceclaim.txt", [xy])
        np.savetxt(out_cad / f"{name}_fusion.csv", np.column_stack(
            [100 * xy, np.zeros(len(xy))]), delimiter=",", fmt="%.5f")
    write_spaceclaim(out_cfd / "domain_spaceclaim.txt",
                     [dom["periodic_upper"], dom["periodic_lower"], dom["inlet"], dom["outlet"]])

    p2 = outlet_static_pressure(s)
    bc = {
        "frame": "rotor (relative). x axial, y tangential, angles from axial",
        "inlet_total_pressure_Pa": round(s.p0_rel, 1),
        "inlet_static_pressure_Pa_initial_guess": round(s.p1, 1),
        "inlet_total_temperature_K": round(s.t0_rel, 2),
        "inlet_flow_angle_deg": round(s.beta1, 3),
        "inlet_direction_xy": [round(math.cos(math.radians(s.beta1)), 5),
                               round(math.sin(math.radians(s.beta1)), 5)],
        "outlet_static_pressure_Pa": round(p2, 1),
        "inlet_rel_mach": round(s.mach_w1, 4),
        "reynolds_chord": round(s.reynolds, -3),
        "turbulence_intensity_pct": 5, "turbulent_viscosity_ratio": 10,
        "chord_mm": round(1000 * s.chord, 3), "pitch_mm": round(1000 * s.pitch, 3),
        "axial_chord_mm": round(1000 * dom["axial_chord"], 3),
        "stagger_deg": round(ang["stagger"], 3), "camber_deg": round(ang["camber"], 3),
        "exit_flow_angle_design_deg": round(s.beta2, 3),
        "roughness_fouled_um": KS_FOULED_UM, "erosion_depth_chord_frac": ERODE_DEPTH,
    }
    (ROOT / "cfd" / "cascade_conditions.json").write_text(json.dumps(bc, indent=2))

    # Figure: three healthy blades with the passage, and a zoom on the leading edge
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(11, 5))
    for k in (-1, 0, 1):
        a1.fill(*(shapes["healthy"] + [0, k * s.pitch]).T, color="0.75", ec="k", lw=0.8)
    for key, c in [("periodic_upper", "C0"), ("periodic_lower", "C0"),
                   ("inlet", "C2"), ("outlet", "C3")]:
        a1.plot(*dom[key].T, color=c, lw=1.2)
    a1.set_title(f"HPC stage {s.number} rotor cascade (mean line)\n"
                 f"chord {1000 * s.chord:.1f} mm, pitch {1000 * s.pitch:.1f} mm, "
                 f"M = {s.mach_w1:.2f}, flow {s.beta1:.0f} -> {s.beta2:.0f} deg")
    a1.set_aspect("equal")
    a1.set_xlabel("axial (m)")
    a1.set_ylabel("tangential (m)")
    for name, c in [("healthy", "k"), ("eroded", "C3")]:
        a2.plot(*(1000 * shapes[name]).T, color=c, lw=1.2, label=name)
    a2.set_xlim(-0.5, 2.5)
    a2.set_ylim(-1, 2)
    a2.set_aspect("equal")
    a2.set_title(f"Leading edge: erosion removes {100 * ERODE_DEPTH:.0f} % of chord")
    a2.set_xlabel("axial (mm)")
    a2.legend()
    fig.tight_layout()
    fig_path = ROOT / "reports" / "figures" / "13_hpc_blade_cascade.png"
    fig.savefig(fig_path, dpi=150)

    print(f"Blade: stagger {ang['stagger']:.1f} deg, camber {ang['camber']:.1f} deg, "
          f"deviation {ang['deviation']:.1f} deg, t/c {THICKNESS}")
    print(f"Outlet static pressure {p2 / 1e5:.3f} bar "
          f"(inlet relative total {s.p0_rel / 1e5:.3f} bar)")
    print("Wrote cfd/geometry/*.txt, cfd/cascade_conditions.json, "
          "cad/blade_profiles/*.csv, " + str(fig_path.relative_to(ROOT)))


if __name__ == "__main__":
    main()
